/** One-shot generator: emits textbook word files from compact data.
 *  Run: node scripts/gen-textbooks.mjs
 *  Word row: [word, pos, zh, example?, exampleZh?] — missing example auto-filled. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'src/data/textbooks');

function entry(bookId, unit, unitTitle, row) {
  const [word, pos, zh, example, exampleZh] = row;
  return {
    id: `${bookId}-${unit}-${String(word).replace(/[^a-z0-9]/gi, '').slice(0, 12)}`.toLowerCase(),
    bookId, unit, unitTitle,
    word, phonetic: '', pos: pos || '', zh,
    enDef: '', example: example || `${word}.`, exampleZh: exampleZh || zh,
  };
}

export const DATA = {};

export function addBook(shelfId, bookId, units) {
  if (!DATA[shelfId]) DATA[shelfId] = {};
  DATA[shelfId][bookId] = units;
}

export function emitAll() {
  let total = 0;
  for (const [shelfId, books] of Object.entries(DATA)) {
    const dir = join(outRoot, shelfId);
    mkdirSync(dir, { recursive: true });
    for (const [bookId, units] of Object.entries(books)) {
      const words = [];
      units.forEach(([unitId, unitTitle, rows]) => {
        rows.forEach((r) => words.push(entry(bookId, unitId, unitTitle, r)));
      });
      const code = `// AUTO-GENERATED by scripts/gen-textbooks.mjs — PEP ${shelfId} · ${bookId}\nexport const bookId = ${JSON.stringify(bookId)};\nexport const words = ${JSON.stringify(words)};\n`;
      writeFileSync(join(dir, `${bookId}.js`), code);
      total += words.length;
    }
  }
  return total;
}

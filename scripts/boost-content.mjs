function fixOptions(opts) {
  if (!opts) return opts;
  return opts.map((o) => {
    o = String(o).replace(/\s*选项 option$/u, '').trim();
    if (OPTION_FIX[o]) return OPTION_FIX[o];
    if (FORMULA_OPT_ZH[o]) return FORMULA_OPT_ZH[o];
    // strip prior formula tag then remap
    const bare = o.replace(/（数值\/公式 value\/formula）$/u, '').trim();
    if (FORMULA_OPT_ZH[bare]) return FORMULA_OPT_ZH[bare];
    const hasZh = /[\u4e00-\u9fff]/.test(o);
    if (hasZh) return o;
    if (/[=×·²³₁₂₄₅⁻⁺]/.test(o) || /^[\d.,×xX\s]+m/.test(o) || /^[\d.]+$/.test(o)) {
      return `${o}（数值/公式 value/formula）`;
    }
    return o;
  });
}

function bilingualizeQuestion(q) {
  const out = {
    ...q,
    prompt: fixPrompt(q.prompt),
    explain: fixExplain(q),
  };
  if (q.type === 'mcq' && q.options) {
    out.options = fixOptions(q.options);
  }
  return out;
}

function tip(zh, en) {
  return `${zh} / ${en}`;
}



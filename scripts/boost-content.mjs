function serializeArray(name, arr, headerComment) {
  const body = JSON.stringify(arr, null, 2)
    // Keep valid JS; JSON is fine for data files
    ;
  return `${headerComment}\nexport const ${name} = ${body};\n`;
}

function uniqueById(items) {
  const map = new Map();
  for (const item of items) map.set(item.id, item);
  return [...map.values()];
}

function pickSlice(ids, start, count, extra = []) {
  const out = [];
  const n = ids.length;
  for (let i = 0; i < count; i++) out.push(ids[(start + i) % n]);
  for (const e of extra) if (!out.includes(e)) out.push(e);
  // dedupe preserving order
  return [...new Set(out)];
}


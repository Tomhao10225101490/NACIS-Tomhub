function fixPrompt(p) {
  return String(p)
    .replace(/\\n/g, ' / ')
    .replace(/\n/g, ' / ')
    .replace(/\s+\/\s+/g, ' / ')
    .trim();
}

function fixExplain(q) {
  let e = String(q.explain || '')
    .replace(/\\n/g, ' / ')
    .replace(/\n/g, ' / ');
  const enMap = EXPLAIN_EN[q.id];
  const parts = e.split(/\s*\/\s*/).map((p) => p.trim()).filter(Boolean);
  const zhSide = parts[0] || e;
  const enSide = parts.slice(1).join(' / ');
  const enStrong = /[A-Za-z]{4,}/.test(enSide);
  if (enMap) {
    // Prefer curated English when missing or weak
    if (!enSide || !enStrong || enSide === zhSide) {
      e = `${zhSide} / ${enMap}`;
    } else {
      e = `${zhSide} / ${enSide}`;
    }
  } else if (!e.includes('/')) {
    e = `${e} / (See curriculum notes.)`;
  } else if (!enStrong && /[A-Za-z]{2,}/.test(enSide)) {
    // short English like "Red" / "Air" — expand lightly
    e = `${zhSide} / ${enSide}`;
  }
  return e.replace(/\s+\/\s+/g, ' / ').trim();
}

